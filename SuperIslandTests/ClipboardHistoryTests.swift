import AppKit
import XCTest
@testable import SuperIsland

@MainActor
final class ClipboardHistoryTests: XCTestCase {
    func testRecordingBeginsWithNextCopyAndPausesCleanly() throws {
        try withFixture { history, board, _, _ in
            write("before enabling", to: board)
            history.poll()
            XCTAssertTrue(history.records.isEmpty)
            history.updateRecording(true)
            history.poll()
            XCTAssertTrue(history.records.isEmpty)
            write("captured after enabling", to: board)
            history.poll()
            XCTAssertEqual(history.records.first?.text, "captured after enabling")
            history.updateRecording(false)
            write("while paused", to: board)
            history.poll()
            XCTAssertEqual(history.records.count, 1)
        }
    }

    func testConcealedAndTransientItemsNeverReachHistory() throws {
        try withFixture { history, board, _, source in
            history.updateRecording(true)
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType"] {
                write("private clipboard sample", to: board, marker: marker)
                history.poll()
            }
            source.bundleID = "com.apple.Passwords"
            write("password manager sample", to: board)
            history.poll()
            XCTAssertTrue(history.records.isEmpty)
            source.bundleID = "com.apple.TextEdit"
            write("ordinary copy", to: board)
            history.poll()
            XCTAssertEqual(history.records.first?.text, "ordinary copy")
        }
    }

    func testPinnedDuplicateRestoresClipboardAndSurvivesReload() throws {
        try withFixture { history, board, url, _ in
            history.updateRecording(true)
            let link = "https://example.org/reference"
            write(link, to: board)
            history.poll()
            let original = try XCTUnwrap(history.records.first)
            history.setPinned(original)
            write("another item", to: board)
            history.poll()
            write(link, to: board)
            history.poll()
            XCTAssertEqual(history.records.count, 2)
            let restored = try XCTUnwrap(history.records.first)
            XCTAssertEqual(restored.id, original.id)
            XCTAssertEqual(restored.kind, .link)
            XCTAssertTrue(restored.pinned)
            XCTAssertTrue(history.copy(restored))
            XCTAssertEqual(board.string(forType: .URL), link)
            history.poll()
            XCTAssertEqual(history.records.count, 2)
            let reloaded = ClipboardHistoryStore(url: url, pasteboard: { board })
            XCTAssertEqual(reloaded.records, history.records)
            reloaded.clear(keepingPinned: true)
            XCTAssertEqual(reloaded.records.map(\.id), [original.id])
            reloaded.clear(keepingPinned: false)
            XCTAssertFalse(FileManager.default.fileExists(atPath: url.path))
        }
    }

    func testFileURLsAndImageDataRoundTrip() throws {
        try withFixture { history, board, _, _ in
            history.updateRecording(true)
            let file = URL(fileURLWithPath: "/tmp/SuperIsland clipboard test.txt")
            let fileItem = NSPasteboardItem()
            fileItem.setString(file.absoluteString, forType: .fileURL)
            board.clearContents()
            XCTAssertTrue(board.writeObjects([fileItem]))
            history.poll()
            let fileRecord = try XCTUnwrap(history.records.first)
            XCTAssertEqual(fileRecord.kind, .files)
            XCTAssertEqual(fileRecord.files, [file])

            let image = try XCTUnwrap(Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aefcAAAAASUVORK5CYII="))
            let imageItem = NSPasteboardItem()
            imageItem.setData(image, forType: .png)
            board.clearContents()
            XCTAssertTrue(board.writeObjects([imageItem]))
            history.poll()
            let imageRecord = try XCTUnwrap(history.records.first)
            XCTAssertEqual(imageRecord.kind, .image)
            XCTAssertTrue(history.copy(imageRecord))
            XCTAssertEqual(board.data(forType: .png), image)
        }
    }

    private final class Source {
        var bundleID = "com.apple.TextEdit"
    }

    private func withFixture(_ body: (ClipboardHistoryStore, NSPasteboard, URL, Source) throws -> Void) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let url = directory.appendingPathComponent("history.plist")
        let board = NSPasteboard.withUniqueName()
        let source = Source()
        let store = ClipboardHistoryStore(url: url, pasteboard: { board }, sourceBundleID: { source.bundleID })
        defer {
            store.updateRecording(false)
            board.releaseGlobally()
            try? FileManager.default.removeItem(at: directory)
        }
        try body(store, board, url, source)
    }

    private func write(_ value: String, to board: NSPasteboard, marker: String? = nil) {
        let item = NSPasteboardItem()
        item.setString(value, forType: .string)
        if let marker { item.setString("", forType: .init(marker)) }
        board.clearContents()
        XCTAssertTrue(board.writeObjects([item]))
    }
}
