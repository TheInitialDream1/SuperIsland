import AppKit
import Combine
import CryptoKit

struct ClipboardRecord: Identifiable, Codable, Equatable {
    enum Kind: String, Codable, CaseIterable, Identifiable {
        case text, link, image, files

        var id: String { rawValue }
        var title: String {
            switch self {
            case .text: return L10n.string("Text")
            case .link: return L10n.string("Links")
            case .image: return L10n.string("Images")
            case .files: return L10n.string("Files")
            }
        }
        var icon: String {
            switch self {
            case .text: return "text.alignleft"
            case .link: return "link"
            case .image: return "photo"
            case .files: return "doc"
            }
        }
    }

    var id = UUID()
    let kind: Kind
    var date = Date()
    var pinned = false
    var text: String? = nil
    var files: [URL]? = nil
    var imageData: Data? = nil
    var imageType: String? = nil

    var summary: String {
        switch kind {
        case .text, .link:
            return text?.prefix(240).split(whereSeparator: \.isNewline).joined(separator: " ") ?? ""
        case .image: return L10n.string("Images")
        case .files:
            return files?.prefix(3).map(\.lastPathComponent).joined(separator: " · ") ?? ""
        }
    }

    var byteCount: Int {
        let textBytes = text?.utf8.count ?? 0
        let imageBytes = imageData?.count ?? 0
        let fileBytes = files?.reduce(0) { $0 + $1.absoluteString.utf8.count } ?? 0
        return textBytes + imageBytes + fileBytes
    }

    var contentKey: String {
        let data = imageData ?? Data((text ?? files?.map(\.absoluteString).joined(separator: "\n") ?? "").utf8)
        return kind.rawValue + ":" + SHA256.hash(data: data).description
    }
}

@MainActor
final class ClipboardHistoryStore: ObservableObject {
    static let shared = ClipboardHistoryStore()
    static let enabledKey = "module.clipboard.enabled"
    static let retentionKey = "module.clipboard.retentionDays"
    static let retentionOptions = [1, 7, 30]

    // These marker types are also used by password managers to prevent
    // clipboard history tools from recording transient/private items.
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]
    static let ignoredAppPrefixes = [
        "com.1password.", "com.agilebits.onepassword", "com.bitwarden.",
        "com.apple.Passwords", "com.apple.keychainaccess", "com.lastpass.",
        "com.dashlane.", "org.keepassxc."
    ]

    @Published private(set) var records: [ClipboardRecord]
    @Published private(set) var isRecording = false
    @Published private(set) var storageError = false

    private let url: URL
    private let defaults: UserDefaults
    private let pasteboard: () -> NSPasteboard
    private let sourceBundleID: () -> String?
    private var timer: Timer?
    private var lastChange: Int?
    private var nextPrune = Date.distantPast
    private let maxCount = 100
    private let maxBytes = 20 * 1024 * 1024
    private let maxItemBytes = 5 * 1024 * 1024

    init(url: URL? = nil, defaults: UserDefaults = .standard,
         pasteboard: @escaping () -> NSPasteboard = { .general },
         sourceBundleID: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        self.url = url ?? URL.applicationSupportDirectory
            .appendingPathComponent("SuperIsland", isDirectory: true)
            .appendingPathComponent("Clipboard", isDirectory: true)
            .appendingPathComponent("History.plist")
        self.defaults = defaults
        self.pasteboard = pasteboard
        self.sourceBundleID = sourceBundleID
        records = (try? Data(contentsOf: self.url))
            .flatMap { try? PropertyListDecoder().decode([ClipboardRecord].self, from: $0) } ?? []
        prune()
    }

    func updateRecording(_ enabled: Bool) {
        guard enabled != isRecording else { return }
        isRecording = enabled
        timer?.invalidate()
        timer = nil
        lastChange = nil
        guard enabled else { return }
        // Do not import what was on the clipboard before the user enabled history.
        lastChange = pasteboard().changeCount
        prune()
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    deinit { timer?.invalidate() }

    func poll() {
        guard isRecording else { return }
        let now = Date()
        if now >= nextPrune { prune(now: now) }
        let board = pasteboard()
        let change = board.changeCount
        guard change != lastChange else { return }
        lastChange = change
        if let id = sourceBundleID(),
           Self.ignoredAppPrefixes.contains(where: { id.lowercased().hasPrefix($0.lowercased()) }) {
            return
        }
        guard let items = board.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              let record = read(items, from: board, at: now),
              board.changeCount == change else { return }
        insert(record)
    }

    @discardableResult
    func copy(_ record: ClipboardRecord) -> Bool {
        let items: [NSPasteboardItem]
        switch record.kind {
        case .text, .link:
            guard let text = record.text else { return false }
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            if record.kind == .link { item.setString(text, forType: .URL) }
            items = [item]
        case .image:
            guard let data = record.imageData, let type = record.imageType else { return false }
            let item = NSPasteboardItem()
            item.setData(data, forType: .init(type))
            items = [item]
        case .files:
            guard let urls = record.files, !urls.isEmpty else { return false }
            items = urls.map { url in
                let item = NSPasteboardItem()
                item.setString(url.absoluteString, forType: .fileURL)
                return item
            }
        }
        let board = pasteboard()
        board.clearContents()
        let written = board.writeObjects(items)
        lastChange = board.changeCount
        return written
    }

    func setPinned(_ record: ClipboardRecord) {
        guard let index = records.firstIndex(where: { $0.id == record.id }) else { return }
        records[index].pinned.toggle()
        prune(save: false)
        persist()
    }

    func remove(_ record: ClipboardRecord) {
        records.removeAll { $0.id == record.id }
        persist()
    }

    func clear(keepingPinned: Bool) {
        records = keepingPinned ? records.filter(\.pinned) : []
        persist()
    }

    func prune(now: Date = Date(), save: Bool = true) {
        let days = defaults.object(forKey: Self.retentionKey) as? Int ?? 7
        let limit = now.addingTimeInterval(-TimeInterval(max(1, min(30, days))) * 86_400)
        var bytes = 0
        var kept: [ClipboardRecord] = []
        for record in records.sorted(by: { lhs, rhs in
            lhs.pinned == rhs.pinned ? lhs.date > rhs.date : lhs.pinned
        }) where record.pinned || record.date >= limit {
            let size = record.byteCount
            guard kept.count < maxCount, size <= maxItemBytes, bytes + size <= maxBytes else { continue }
            bytes += size
            kept.append(record)
        }
        nextPrune = now.addingTimeInterval(3600)
        guard kept != records else { return }
        records = kept
        if save { persist() }
    }

    private func insert(_ incoming: ClipboardRecord) {
        var record = incoming
        let key = incoming.contentKey
        if let index = records.firstIndex(where: { $0.kind == incoming.kind && $0.contentKey == key }) {
            let previous = records.remove(at: index)
            record.id = previous.id
            record.pinned = previous.pinned
        }
        records.insert(record, at: 0)
        prune(now: record.date, save: false)
        persist()
    }

    private func read(_ items: [NSPasteboardItem], from board: NSPasteboard, at now: Date) -> ClipboardRecord? {
        let fileURLs = items.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }
            .filter(\.isFileURL)
        if !fileURLs.isEmpty {
            return ClipboardRecord(kind: .files, date: now, files: Array(fileURLs.prefix(100)))
        }
        if let item = items.first {
            for type in [NSPasteboard.PasteboardType.png, .tiff] {
                if let data = item.data(forType: type), !data.isEmpty, data.count <= maxItemBytes {
                    return ClipboardRecord(kind: .image, date: now, imageData: data, imageType: type.rawValue)
                }
            }
        }
        guard let value = board.string(forType: .URL) ?? board.string(forType: .string),
              !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              value.utf8.count <= 256 * 1024 else { return nil }
        let kind: ClipboardRecord.Kind = URL(string: value)?.scheme.map {
            ["http", "https"].contains($0.lowercased()) && !value.contains(where: \.isWhitespace)
        } == true ? .link : .text
        return ClipboardRecord(kind: kind, date: now, text: value)
    }

    private func persist() {
        do {
            if records.isEmpty {
                if FileManager.default.fileExists(atPath: url.path) {
                    try FileManager.default.removeItem(at: url)
                }
            } else {
                try FileManager.default.createDirectory(at: url.deletingLastPathComponent(),
                                                        withIntermediateDirectories: true,
                                                        attributes: [.posixPermissions: 0o700])
                let encoder = PropertyListEncoder()
                encoder.outputFormat = .binary
                try encoder.encode(records).write(to: url, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            }
            storageError = false
        } catch {
            storageError = true
        }
    }
}
